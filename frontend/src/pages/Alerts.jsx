import React, { useEffect, useState } from 'react';
import { useSearchParams, Link } from 'react-router-dom';
import { fetchAlerts } from '../services/api';
import { Search, ChevronLeft, ChevronRight, ShieldAlert, ArrowUpRight } from 'lucide-react';

export default function Alerts() {
  const [searchParams, setSearchParams] = useSearchParams();
  const [alerts, setAlerts] = useState([]);
  const [pagination, setPagination] = useState({ page: 1, limit: 20, total: 0, total_pages: 1 });
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const search = searchParams.get('search') || '';
  const status = searchParams.get('status') || '';
  const ruleCode = searchParams.get('rule_code') || '';
  const page = parseInt(searchParams.get('page'), 10) || 1;

  useEffect(() => {
    setLoading(true);
    fetchAlerts({
      page,
      limit: 20,
      search,
      status,
      rule_code: ruleCode
    })
      .then(res => {
        setAlerts(res.data);
        setPagination(res.pagination);
        setLoading(false);
      })
      .catch(err => {
        setError(err.message);
        setLoading(false);
      });
  }, [page, search, status, ruleCode]);

  const updateFilter = (key, value) => {
    const next = new URLSearchParams(searchParams);
    if (value) next.set(key, value);
    else next.delete(key);
    next.set('page', '1');
    setSearchParams(next);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div>
        <h1 className="text-xl font-semibold text-[#111827] tracking-tight">Fraud Alerts</h1>
        <p className="text-xs text-[#6b7280] mt-1">
          Compliance review queue generated by deterministic relational SQL fraud rules.
        </p>
      </div>

      {/* Filter and Search Bar */}
      <div className="bg-white border border-[#e5e7eb] rounded-lg p-3 flex flex-wrap items-center gap-3">
        <div className="relative flex-1 min-w-[200px]">
          <Search className="w-4 h-4 absolute left-3 top-2.5 text-[#9ca3af]" />
          <input
            type="text"
            placeholder="Search by transaction reference..."
            value={search}
            onChange={e => updateFilter('search', e.target.value)}
            className="w-full pl-9 pr-3 py-1.5 text-xs bg-[#f9fafb] border border-[#e5e7eb] rounded focus:outline-none focus:border-[#4f46e5]"
          />
        </div>

        <select
          value={status}
          onChange={e => updateFilter('status', e.target.value)}
          className="text-xs bg-[#f9fafb] border border-[#e5e7eb] rounded px-2.5 py-1.5 text-[#374151] focus:outline-none focus:border-[#4f46e5]"
        >
          <option value="">All Review Statuses</option>
          <option value="PENDING">Pending</option>
          <option value="REVIEWED">Reviewed</option>
          <option value="CONFIRMED_FRAUD">Confirmed Fraud</option>
          <option value="FALSE_POSITIVE">False Positive</option>
        </select>

        <select
          value={ruleCode}
          onChange={e => updateFilter('rule_code', e.target.value)}
          className="text-xs bg-[#f9fafb] border border-[#e5e7eb] rounded px-2.5 py-1.5 text-[#374151] focus:outline-none focus:border-[#4f46e5]"
        >
          <option value="">All Rules</option>
          <option value="RULE_HIGH_VAL">High-Value Transaction</option>
          <option value="RULE_RAPID_TX">Rapid Successive Transactions</option>
          <option value="RULE_REPEAT_TRANSFER">Repeated Transfers</option>
        </select>
      </div>

      {/* Alerts Table */}
      <div className="bg-white border border-[#e5e7eb] rounded-lg overflow-hidden">
        {loading ? (
          <div className="py-20 flex flex-col items-center justify-center text-xs text-[#6b7280]">
            <div className="w-5 h-5 border-2 border-[#111827] border-t-transparent rounded-full animate-spin mb-2" />
            <span>Fetching alert queue...</span>
          </div>
        ) : error ? (
          <div className="p-6 text-center text-xs text-[#b91c1c]">{error}</div>
        ) : alerts.length === 0 ? (
          <div className="p-12 text-center text-xs text-[#6b7280]">No alerts match specified filters.</div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs">
              <thead className="bg-[#f9fafb] text-[#6b7280] border-b border-[#e5e7eb]">
                <tr>
                  <th className="px-4 py-2.5 font-medium">Alert ID</th>
                  <th className="px-4 py-2.5 font-medium">Tx Reference</th>
                  <th className="px-4 py-2.5 font-medium">Rule Triggered</th>
                  <th className="px-4 py-2.5 font-medium">Severity</th>
                  <th className="px-4 py-2.5 font-medium">Risk Score</th>
                  <th className="px-4 py-2.5 font-medium">Amount</th>
                  <th className="px-4 py-2.5 font-medium">Review Status</th>
                  <th className="px-4 py-2.5 font-medium">Triggered At</th>
                  <th className="px-4 py-2.5 font-medium text-right">Investigation</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-[#f3f4f6]">
                {alerts.map(a => (
                  <tr key={a.alert_id} className="hover:bg-[#f9fafb] transition-colors">
                    <td className="px-4 py-3 font-mono text-[11px] text-[#6b7280]">
                      #{a.alert_id}
                    </td>
                    <td className="px-4 py-3 font-mono text-[11px] text-[#111827] font-medium">
                      {a.transaction_reference}
                    </td>
                    <td className="px-4 py-3 text-[#111827]">{a.rule_name}</td>
                    <td className="px-4 py-3">
                      <span className={`px-2 py-0.5 rounded text-[10px] font-medium ${
                        a.rule_severity === 'CRITICAL' ? 'bg-[#fef2f2] text-[#991b1b]' :
                        a.rule_severity === 'HIGH' ? 'bg-[#fffbeb] text-[#92400e]' :
                        'bg-[#f3f4f6] text-[#374151]'
                      }`}>
                        {a.rule_severity}
                      </span>
                    </td>
                    <td className="px-4 py-3 tabular-nums font-semibold text-[#111827]">
                      {a.risk_score}
                    </td>
                    <td className="px-4 py-3 tabular-nums text-[#111827]">
                      ${a.transaction_amount.toLocaleString('en-US', { minimumFractionDigits: 2 })}
                    </td>
                    <td className="px-4 py-3">
                      <span className={`px-2 py-0.5 rounded text-[10px] font-medium ${
                        a.status === 'PENDING' ? 'bg-[#fffbeb] text-[#b45309]' :
                        a.status === 'CONFIRMED_FRAUD' ? 'bg-[#fef2f2] text-[#b91c1c]' :
                        a.status === 'FALSE_POSITIVE' ? 'bg-[#f3f4f6] text-[#4b5563]' :
                        'bg-[#ecfdf5] text-[#065f46]'
                      }`}>
                        {a.status}
                      </span>
                    </td>
                    <td className="px-4 py-3 text-[#6b7280]">
                      {new Date(a.triggered_at).toLocaleString([], { month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' })}
                    </td>
                    <td className="px-4 py-3 text-right">
                      <Link
                        to={`/alerts/${a.alert_id}`}
                        className="inline-flex items-center gap-1 text-xs font-medium text-[#4f46e5] hover:text-[#4338ca]"
                      >
                        <span>Triage</span>
                        <ArrowUpRight className="w-3.5 h-3.5" />
                      </Link>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}

        {/* Pagination Footer */}
        <div className="px-4 py-3 border-t border-[#e5e7eb] flex items-center justify-between text-xs text-[#6b7280]">
          <span>
            Page <span className="font-semibold text-[#111827]">{pagination.page}</span> of{' '}
            <span className="font-semibold text-[#111827]">{pagination.total_pages}</span> ({pagination.total} alerts)
          </span>
          <div className="flex items-center gap-2">
            <button
              disabled={pagination.page <= 1}
              onClick={() => updateFilter('page', String(pagination.page - 1))}
              className="p-1 rounded border border-[#e5e7eb] disabled:opacity-40 hover:bg-[#f9fafb]"
            >
              <ChevronLeft className="w-4 h-4" />
            </button>
            <button
              disabled={pagination.page >= pagination.total_pages}
              onClick={() => updateFilter('page', String(pagination.page + 1))}
              className="p-1 rounded border border-[#e5e7eb] disabled:opacity-40 hover:bg-[#f9fafb]"
            >
              <ChevronRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
